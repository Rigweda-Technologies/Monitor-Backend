import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import mongoose from 'mongoose';
import bcrypt from 'bcryptjs';
import jwt from 'jsonwebtoken';
import { createLegacyHarness } from './helpers/legacy-harness.js';
import { createRuntime } from '../src/runtime.js';
import { createModels } from '../src/modules/auth/auth.models.js';
import { loadConfig } from '../src/config/env.js';
const uri=process.env.V2_HRMS_ISOLATED_TEST_DATABASE_URL;
test('raw legacy session fields and absent schema defaults remain readable and login can rotate session',{skip:!uri},async t=>{
  assert.match(new URL(uri).pathname,/[_-](test|isolated|ci)([_-]|$)/i);
  const config=loadConfig({MONGODB_URI:uri,JWT_SECRET:randomBytes(32).toString('hex'),BCRYPT_SALT_ROUNDS:'4'});
  const connection=await mongoose.createConnection(uri,{autoCreate:false,autoIndex:false}).asPromise();
  const models=createModels(connection);
  const ids={user:new mongoose.Types.ObjectId(),org:new mongoose.Types.ObjectId(),role:new mongoose.Types.ObjectId()};
  const email=`legacy-${ids.user}@example.com`,password=randomBytes(12).toString('hex');
  const runtime=await createRuntime({config,connection,logger:false,sendOtp:async()=>{},verifySelfie:async()=>({confidence:99})});
  const legacy=createLegacyHarness({models,config,sendMail:async()=>true,faceFetch:async()=>({json:async()=>({})})});
  const server=legacy.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));for(const model of Object.values(models)) await model.deleteMany({$or:[{_id:{$in:Object.values(ids)}},{userId:ids.user},{organizationId:ids.org}]});await runtime.close();await connection.close();});
  const passwordHash=await bcrypt.hash(password,4);
  const date=new Date('2026-10-01T00:00:00Z');
  await models.Organization.collection.insertOne({_id:ids.org,name:'Legacy Org',code:String(ids.org),timezone:'Asia/Kolkata',currency:'INR',createdAt:date,updatedAt:date});
  await models.Role.collection.insertOne({_id:ids.role,organizationId:ids.org,name:'Employee',slug:'employee',createdAt:date,updatedAt:date});
  await models.Membership.collection.insertOne({userId:ids.user,organizationId:ids.org,roleIds:[ids.role],createdAt:date,updatedAt:date});
  const legacyToken=jwt.sign({userId:ids.user,organizationId:ids.org,roleIds:[ids.role],activeRoleId:ids.role},config.jwtSecret,{expiresIn:'1d'});
  await models.User.collection.insertOne({_id:ids.user,email,password:passwordHash,organizationIds:[ids.org],tokenList:[{token:legacyToken,loginTimestamp:date.toISOString(),status:'active'}],createdAt:date,updatedAt:date});
  const legacyUser=await models.User.findById(ids.user).lean();
  assert.equal(legacyUser.status,undefined);
  assert.equal(legacyUser.tokenList[0].organizationId,undefined);
  const profile=await runtime.app.inject({url:'/api/v2/users/me/profile',headers:{authorization:`Bearer ${legacyToken}`}});
  assert.equal(profile.statusCode,200,profile.body);
  const v1profile=await fetch(`http://127.0.0.1:${server.address().port}/api/v1/users/me/profile`,{headers:{authorization:`Bearer ${legacyToken}`}});
  assert.equal(v1profile.status,200);
  assert.deepEqual(profile.json(),await v1profile.json());
  const login=await runtime.app.inject({method:'POST',url:'/api/v2/users/login',payload:{email,password}});
  assert.equal(login.statusCode,200,login.body);
  const stored=await models.User.collection.findOne({_id:ids.user});
  assert.equal(stored.tokenList.length,2);
  assert.equal(stored.tokenList[1].token,legacyToken);
  assert.equal(stored.tokenList[1].organizationId,undefined);
  assert.equal(stored.status,undefined,'v2 login preserves legacy stored fields');
  assert.equal(login.json().data.organization.status,'active');
  assert.equal(login.json().data.organization.leaveCycleStartMonth,1);
  assert.equal(login.json().data.roles[0].isSystemRole,false);
  assert.equal(login.json().data.roles[0].status,'active');
});
